#!/usr/bin/env python3
"""Generate API.md (the modding API reference) from Stackflow's GDScript doc comments.

Runs Godot's doctool on the game project, then converts the XML of the curated classes
below into Markdown. Re-run it after changing the game's public API:

    python3 tools/generate_api.py --game ../stackflow [--godot godot]

Only classes/members listed in CLASSES are documented: they are the API mods are meant
to use. `None` means every public member (names not starting with "_").
"""

import argparse
import re
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

CLASSES: dict[str, dict | None] = {
    "BaseBlock": {
        "methods": ["_init", "set_complexity", "set_destroy_effect", "get_destroy_effect",
                    "set_on_place", "set_on_block_destroyed"],
        "members": ["id", "groups", "min_amount", "max_amount", "recipe", "price", "unlock_round",
                    "complexity", "texture_path"],
    },
    "DestroyEffectContext": None,
    "BlockRegistry": None,
    "PlacedBlock": {
        "methods": ["get_center_position", "morph", "pulse_animation", "get_adjacent_blocks",
                    "get_adjacent_blocks_of_type", "get_blocks_in_range", "get_blocks_in_range_of_type",
                    "collect_connected_chain", "get_connected_chain_neighbors", "destroy"],
        "members": ["type", "grid_position", "custom_variables", "destroy_animation_requested",
                    "activation_count"],
        "signals": ["destroyed"],
    },
    "GameManager": {
        "methods": ["add_points", "add_multiplier", "add_credits", "get_blocks_of_type",
                    "get_blocks_of_group", "has_block_type_in_original_deck", "is_game_busy"],
        "members": ["current_round", "timescale"],
        "signals": ["piece_landed", "block_destroyed", "points_changed", "multiplier_changed"],
    },
    "GameData": {
        "methods": ["get_block_name", "get_block_texture", "get_block_texture_path",
                    "load_texture", "is_block_on_group"],
        "constants": ["BlockGroups", "MID_GAME_ROUND", "FINAL_GAME_ROUND"],
    },
    "PointNotification": {
        "methods": ["create_and_slide"],
        "constants": ["UP", "DOWN", "BLUE", "RED", "GRAY", "YELLOW"],
    },
    "AudioManager": {
        "methods": ["play"],
        "constants": ["SoundEffects"],
    },
    "Random": {
        "methods": ["randf", "randf_range", "randi", "randi_range", "pick_random", "shuffle"],
    },
}

INTRO = """# Stackflow modding API

> Generated by `tools/generate_api.py` from the game's doc comments. Do not edit by hand.

Autoloads (`BlockRegistry`, `GameManager`, `GameData`, `AudioManager`, `Random`) are global:
call them directly, e.g. `GameManager.add_points(10)`. Use `Random` instead of `randi()`/`randf()`
so runs stay reproducible from their seed.

"""


def bbcode_to_markdown(text: str) -> str:
    """Converts Godot doc BBCode to Markdown."""
    # Doctool indents text with tabs (XML nesting); the code inside codeblocks uses spaces.
    text = "\n".join(line.lstrip("\t").rstrip() for line in text.strip("\n").splitlines()).strip()
    text = re.sub(r"\[codeblock\]\n?(.*?)\n?\[/codeblock\]",
                  lambda m: "\n```gdscript\n" + m.group(1) + "\n```\n", text, flags=re.S)
    text = re.sub(r"\[code\](.*?)\[/code\]", r"`\1`", text)
    text = re.sub(r"\[b\](.*?)\[/b\]", r"**\1**", text)
    text = re.sub(r"\[i\](.*?)\[/i\]", r"*\1*", text)
    text = text.replace("[br]", "  \n")
    text = re.sub(r"\[(?:method) ([\w.]+)\]", r"`\1()`", text)
    text = re.sub(r"\[(?:member|signal|constant|param|enum) ([\w.]+)\]", r"`\1`", text)
    text = re.sub(r"\[([A-Z]\w+)\]", r"`\1`", text)
    return text


def _type(node: ET.Element) -> str:
    return node.get("enum") or node.get("type") or "Variant"


def _params(node: ET.Element) -> str:
    params = []
    for param in sorted(node.findall("param"), key=lambda p: int(p.get("index"))):
        text = f"{param.get('name')}: {_type(param)}"
        if param.get("default") is not None:
            text += f" = {param.get('default')}"
        params.append(text)
    return ", ".join(params)


def _description(node: ET.Element) -> str:
    desc = node.find("description")
    return bbcode_to_markdown(desc.text or "") if desc is not None else ""


def _allowed(name: str, section: str, spec: dict | None) -> bool:
    if spec is None:
        return not name.startswith("_") or name == "_init"
    return name in spec.get(section, [])


def class_to_markdown(root: ET.Element, spec: dict | None) -> str:
    name = root.get("name")
    out = [f"## {name}", f"*Inherits `{root.get('inherits')}`*", ""]

    for tag in ("brief_description", "description"):
        node = root.find(tag)
        if node is not None and (node.text or "").strip():
            out += [bbcode_to_markdown(node.text), ""]

    methods = [m for m in root.iter("method") if _allowed(m.get("name"), "methods", spec)]
    if methods:
        out += ["### Methods", ""]
        for method in methods:
            method_name = method.get("name")
            returns = _type(method.find("return"))
            static = "static " if "static" in (method.get("qualifiers") or "") else ""
            if method_name == "_init":
                signature = f"{name}.new({_params(method)})"
            else:
                signature = f"{static}func {method_name}({_params(method)}) -> {returns}"
            out += [f"#### `{method_name if method_name != '_init' else 'new'}`",
                    f"```gdscript\n{signature}\n```"]
            if description := _description(method):
                out.append(description)
            out.append("")

    members = [m for m in root.iter("member") if _allowed(m.get("name"), "members", spec)]
    if members:
        out += ["### Properties", "", "| Name | Type | Description |", "|---|---|---|"]
        for member in members:
            description = bbcode_to_markdown(member.text or "").replace("\n", " ")
            out.append(f"| `{member.get('name')}` | `{_type(member)}` | {description} |")
        out.append("")

    signals = [s for s in root.iter("signal") if _allowed(s.get("name"), "signals", spec)]
    if signals:
        out += ["### Signals", ""]
        for signal in signals:
            out.append(f"- **`{signal.get('name')}({_params(signal)})`** {_description(signal)}".rstrip())
        out.append("")

    constants = [c for c in root.iter("constant")
                 if _allowed(c.get("enum") or c.get("name"), "constants", spec)
                 or _allowed(c.get("name"), "constants", spec)]
    if constants:
        out += ["### Constants & enums", ""]
        current_enum = None
        for constant in constants:
            enum = constant.get("enum")
            if enum and not enum.startswith("@") and enum != current_enum:
                out += ["", f"**enum `{enum}`**", ""]
                current_enum = enum
            description = bbcode_to_markdown(constant.text or "").replace("\n", " ")
            value = constant.get("value")
            out.append(f"- `{constant.get('name')}` = `{value}` {description}".rstrip())
        out.append("")

    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--game", required=True, type=Path, help="Path to the Stackflow Godot project")
    parser.add_argument("--godot", default="godot", help="Godot executable (same version as the game)")
    parser.add_argument("--out", type=Path, default=Path(__file__).resolve().parent.parent / "API.md")
    args = parser.parse_args()

    with tempfile.TemporaryDirectory() as tmp:
        # --gdscript-docs only accepts folders, so document all of scripts/ and filter.
        subprocess.run(
            [args.godot, "--headless", "--path", str(args.game), "--doctool", tmp, "--gdscript-docs", "res://scripts"],
            check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
        )

        sections = []
        for class_name, spec in CLASSES.items():
            xml_path = Path(tmp) / f"{class_name}.xml"
            if not xml_path.exists():
                print(f"warning: {class_name} not found in the doctool output", file=sys.stderr)
                continue
            sections.append(class_to_markdown(ET.parse(xml_path).getroot(), spec))

    toc = "\n".join(f"- [{name}](#{name.lower()})" for name in CLASSES)
    args.out.write_text(INTRO + toc + "\n\n---\n\n" + "\n\n---\n\n".join(sections) + "\n")
    print(f"Wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
